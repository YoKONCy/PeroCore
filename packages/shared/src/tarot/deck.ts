export const TAROT_SUIT_LABELS: Record<TarotSuit, string> = {
  major: '大阿尔卡那',
  wands: '权杖',
  cups: '圣杯',
  swords: '宝剑',
  pentacles: '星币',
}
const majorIcons = [
  'sparkle',
  'sparkle',
  'moon',
  'heart',
  'shield',
  'book',
  'heart',
  'send',
  'heart',
  'search',
  'refresh',
  'shield',
  'clock',
  'leaf',
  'activity',
  'link',
  'activity',
  'star',
  'moon',
  'sun',
  'volume',
  'globe',
]
const suitIcons = { wands: 'activity', cups: 'heart', swords: 'shield', pentacles: 'star' }
function makeCard(text: CardText, suit: TarotSuit, number: number): TarotCard {
  const [name, keywords, upright, reversed, invitation] = text
  return {
    id: `${suit}-${number}`,
    name: suit === 'major' ? name : `${TAROT_SUIT_LABELS[suit]}${name}`,
    number,
    suit,
    icon: suit === 'major' ? majorIcons[number]! : suitIcons[suit],
    keywords,
    upright,
    reversed,
    invitation,
  }
}
export const TAROT_DECK: readonly TarotCard[] = [
  ...majors.map((text, index) => makeCard(text, 'major', index)),
  ...(['wands', 'cups', 'swords', 'pentacles'] as const).flatMap((suit) =>
    minorTexts[suit].map((text, index) => makeCard(text, suit, index + 1)),
  ),
]
const cardsById = new Map(TAROT_DECK.map((card) => [card.id, card]))
export function getTarotCard(id: string): TarotCard {
  const card = cardsById.get(id)
  if (!card) throw new Error(`未知的塔罗牌：${id}`)
  return card
}
export function tarotMeaning(draw: TarotDraw): string {
  const card = getTarotCard(draw.cardId)
  return draw.reversed ? card.reversed : card.upright
}
